package Day1;

public class FindLargest {
    public static void main(String[] args){
        // two numbers
        int x = 5;
        int y = 10;
        // use if-else to find the largest
        if(x > y){
            System.out.println("Larger number: " +x);
        }
        else{
            System.out.println("Larger number: " +y);
        }
    }
}
